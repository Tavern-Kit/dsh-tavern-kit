import { JSDOM } from 'jsdom';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { installAppearance } from './runtime.js';
import { ThemeLibrary } from './theme-library.js';
import { DEFAULT_APPEARANCE, readAppearancePreferences } from './preferences.js';
import type { AppearancePreferences } from './types.js';
const library = new ThemeLibrary(fileURLToPath(new URL('../themes/', import.meta.url)), join(tmpdir(), `tk-runtime-unused-${process.pid}`));
const layers = () => {
  const values = new Map<string, Record<string, { light: string; dark: string }>>();
  return { values, theme: { overrideTokens(source: string, tokens: Record<string, { light: string; dark: string }>) { values.set(source, tokens); return () => { if (values.get(source) === tokens) values.delete(source); }; } } };
};
describe('appearance lifecycle', () => {
  it('replaces only its own theme layer and restores all host attributes and styles when unloaded', () => {
    const dom = new JSDOM('<!doctype html><html data-tk-skin="previous" data-tk-scheme="host"><head></head><body><div class="tk-rp"><p>剧情继续</p></div></body></html>');
    const context = layers();
    const handle = installAppearance(dom.window.document, context.theme);
    handle.update({ ...DEFAULT_APPEARANCE, skin: 'classic', fontSize: 19 }, library.get('classic'));
    expect(dom.window.document.documentElement.dataset.tkSkin).toBe('classic');
    expect(dom.window.document.documentElement.dataset.tkSceneKind).toBe('image');
    handle.update({ ...DEFAULT_APPEARANCE, skin:'xi4u' }, library.get('xi4u'));
    expect(dom.window.document.documentElement.dataset.tkSceneKind).toBe('xi4u');
    handle.update({ ...DEFAULT_APPEARANCE, skin:'classic',fontSize:19 }, library.get('classic'));
    expect(context.values.get('@tavern-kit/rp-appearance')?.['--tk-font-size']).toEqual({ light: '19px', dark: '19px' });
    handle.update({ ...DEFAULT_APPEARANCE, skin: 'island', bubbles: false }, library.get('island'));
    expect(context.values.size).toBe(1);
    expect(dom.window.document.documentElement.dataset.tkBubbles).toBe('off');
    const textColor = library.get('island').manifest.palettes.light['--tk-text'];
    expect(context.values.get('@tavern-kit/rp-appearance')?.['--tk-text']).toEqual({ light: textColor, dark: textColor });
    expect(dom.window.document.querySelector('.tk-rp p')?.textContent).toBe('剧情继续');
    handle.dispose(); handle.dispose();
    expect(context.values.size).toBe(0);
    expect(dom.window.document.documentElement.dataset.tkSkin).toBe('previous');
    expect(dom.window.document.documentElement.dataset.tkScheme).toBe('host');
    expect(dom.window.document.documentElement.hasAttribute('data-tk-bubbles')).toBe(false);
    expect(dom.window.document.documentElement.hasAttribute('data-tk-scene-kind')).toBe(false);
    expect(dom.window.document.querySelector('style[data-tk-appearance]')).toBeNull();
  });
  it('responds to system changes immediately while a fixed scheme stays fixed, then removes its listener', () => {
    const dom = new JSDOM('<!doctype html><html><head></head><body></body></html>');
    const listeners = new Set<() => void>();
    const query = { matches: false, addEventListener: (_name: string, listener: () => void) => listeners.add(listener), removeEventListener: (_name: string, listener: () => void) => listeners.delete(listener) };
    Object.defineProperty(dom.window, 'matchMedia', { value: () => query });
    const context = layers(); const handle = installAppearance(dom.window.document, context.theme);
    const theme = library.get('island');
    handle.update({ ...DEFAULT_APPEARANCE, skin: 'island', scheme: 'system', season: 'winter' }, theme);
    expect(context.values.get('@tavern-kit/rp-appearance')?.['--tk-bg']?.light).toBe(theme.manifest.palettes.light['--tk-bg']);
    query.matches = true; for (const listener of listeners) listener();
    expect(context.values.get('@tavern-kit/rp-appearance')?.['--tk-bg']?.light).toBe(theme.manifest.palettes.dark['--tk-bg']);
    expect(dom.window.document.documentElement.dataset.tkScheme).toBe('dark');
    expect(dom.window.document.documentElement.dataset.tkSeason).toBe('winter');
    handle.update({ ...DEFAULT_APPEARANCE, skin: 'island', scheme: 'light', season: 'winter' }, theme);
    for (const listener of listeners) listener();
    expect(dom.window.document.documentElement.dataset.tkScheme).toBe('light');
    expect(context.values.get('@tavern-kit/rp-appearance')?.['--tk-bg']?.light).toBe(theme.manifest.palettes.light['--tk-bg']);
    handle.dispose(); expect(listeners.size).toBe(0);
  });
  it('restores the saved pixel theme and reading size on remount without changing the original text', () => {
    const dom = new JSDOM('<!doctype html><html data-tk-skin="host"><head></head><body><div class="tk-rp"><p>同一段剧情</p></div></body></html>');
    const preferences = readAppearancePreferences({ ...DEFAULT_APPEARANCE, skin: 'pixel', fontSize: 23, bubbles: false });
    const context = layers();
    const first = installAppearance(dom.window.document, context.theme); first.update(preferences, library.get('pixel'));
    expect(dom.window.document.documentElement.dataset.tkSkin).toBe('pixel'); first.dispose();
    const restored = installAppearance(dom.window.document, context.theme); restored.update(preferences, library.get('pixel'));
    expect(context.values.get('@tavern-kit/rp-appearance')?.['--tk-font-size']?.light).toBe('23px');
    expect(dom.window.document.querySelector('.tk-rp p')?.textContent).toBe('同一段剧情'); restored.dispose();
    expect(dom.window.document.documentElement.dataset.tkSkin).toBe('host');
    expect(dom.window.document.querySelector('style[data-tk-appearance]')).toBeNull();
  });
  it('uses local custom backgrounds without remote link elements', () => {
    const dom = new JSDOM('<!doctype html><html><head></head><body></body></html>'); const context = layers();
    const handle = installAppearance(dom.window.document, context.theme);
    const preferences: AppearancePreferences = { ...DEFAULT_APPEARANCE, background: 'custom', backgroundImage: 'data:image/png;base64,aGVsbG8=' };
    handle.update(preferences, library.get('classic'));
    expect(context.values.get('@tavern-kit/rp-appearance')?.['--tk-background-image']?.light).toBe('url("data:image/png;base64,aGVsbG8=")');
    handle.update({ ...preferences, background: 'plain' }, library.get('classic'));
    expect(context.values.get('@tavern-kit/rp-appearance')?.['--tk-background-image']?.light).toBe('none');
    handle.update({ ...preferences, skin:'xi4u', background:'custom' }, library.get('xi4u'));
    expect(dom.window.document.documentElement.dataset.tkSceneKind).toBe('none');
    handle.update({ ...preferences, skin:'xi4u', background:'plain' }, library.get('xi4u'));
    expect(dom.window.document.documentElement.dataset.tkSceneKind).toBe('none');
    expect(dom.window.document.querySelectorAll('link')).toHaveLength(0); handle.dispose();
  });
});
